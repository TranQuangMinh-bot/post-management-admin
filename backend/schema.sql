-- ---------------------------------------------------------------------
-- 1. Profiles (one row per auth user, holds the role)
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text,
  full_name   text,
  role        text not null default 'user' check (role in ('user', 'admin')),
  created_at  timestamptz not null default now()
);

-- Auto-create a profile whenever a new auth user is created
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill profiles for users that already exist
insert into public.profiles (id, email)
select id, email from auth.users
on conflict (id) do nothing;

-- ---------------------------------------------------------------------
-- 2. Helper: is the current user an admin?
--    security definer avoids RLS recursion when used inside policies
-- ---------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

-- ---------------------------------------------------------------------
-- 3. Posts
--    attachments: array of Storage object paths, e.g. ["1699999-a.png"]
-- ---------------------------------------------------------------------
create table if not exists public.posts (
  id           bigint generated by default as identity primary key,
  title        text not null check (char_length(title) between 1 and 200),
  content      text not null default '',
  status       text not null default 'draft' check (status in ('draft', 'published', 'hidden')),
  attachments  jsonb not null default '[]'::jsonb,
  author_id    uuid not null default auth.uid() references public.profiles (id),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists posts_status_idx     on public.posts (status);
create index if not exists posts_author_idx     on public.posts (author_id);
create index if not exists posts_created_at_idx on public.posts (created_at desc);

-- Keep updated_at fresh
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists posts_set_updated_at on public.posts;
create trigger posts_set_updated_at
  before update on public.posts
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 4. Row Level Security
--    Only admins can read/write posts. Users can read their own profile
--    but cannot change roles (only admins can update profiles).
-- ---------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.posts    enable row level security;

drop policy if exists "profiles_select_own_or_admin" on public.profiles;
create policy "profiles_select_own_or_admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_update_admin" on public.profiles;
create policy "profiles_update_admin" on public.profiles
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "posts_select_admin" on public.posts;
create policy "posts_select_admin" on public.posts
  for select to authenticated
  using (public.is_admin());

drop policy if exists "posts_insert_admin" on public.posts;
create policy "posts_insert_admin" on public.posts
  for insert to authenticated
  with check (public.is_admin());

drop policy if exists "posts_update_admin" on public.posts;
create policy "posts_update_admin" on public.posts
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "posts_delete_admin" on public.posts;
create policy "posts_delete_admin" on public.posts
  for delete to authenticated
  using (public.is_admin());

-- ---------------------------------------------------------------------
-- 5. Storage bucket for attachments
--    Public read (simple: files open via direct URL), admin-only write.
--    Limit 10 MB per file; images and PDF only.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'post-attachments',
  'post-attachments',
  true,
  10485760,
  array['image/png', 'image/jpeg', 'image/gif', 'image/webp', 'application/pdf']
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "attachments_insert_admin" on storage.objects;
create policy "attachments_insert_admin" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'post-attachments' and public.is_admin());

drop policy if exists "attachments_update_admin" on storage.objects;
create policy "attachments_update_admin" on storage.objects
  for update to authenticated
  using (bucket_id = 'post-attachments' and public.is_admin())
  with check (bucket_id = 'post-attachments' and public.is_admin());

drop policy if exists "attachments_delete_admin" on storage.objects;
create policy "attachments_delete_admin" on storage.objects
  for delete to authenticated
  using (bucket_id = 'post-attachments' and public.is_admin());

